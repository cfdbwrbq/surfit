const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--use-gl=swiftshader','--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  const errors = [];
  page.on('console', (msg) => { if (msg.type() === 'error') errors.push(msg.text()); });
  page.on('pageerror', (err) => errors.push(err.message));
  await page.goto('http://127.0.0.1:8010/', { waitUntil: 'networkidle' });
  await page.setInputFiles('#files', ['examples/points.geojson']);
  await page.click('#solve');
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Done'), null, { timeout: 30000 });
  await page.click('#fullscreen');
  await page.waitForFunction(() => document.fullscreenElement?.id === 'result-pane');
  const active = await page.textContent('#fullscreen');
  if (active !== 'Exit fullscreen') throw new Error('fullscreen label not updated: ' + active);
  await page.evaluate(() => document.exitFullscreen());
  await page.waitForFunction(() => !document.fullscreenElement);
  const inactive = await page.textContent('#fullscreen');
  if (inactive !== 'Fullscreen') throw new Error('fullscreen label not restored: ' + inactive);
  console.log(JSON.stringify({ active, inactive, errors }));
  await browser.close();
})().catch((err) => { console.error(err); process.exit(1); });
