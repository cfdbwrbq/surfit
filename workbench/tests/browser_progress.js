const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--use-gl=swiftshader','--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  const errors = [];
  page.on('console', (msg) => { if (msg.type() === 'error') errors.push(msg.text()); });
  page.on('pageerror', (err) => errors.push(err.message));
  await page.goto('http://127.0.0.1:8010/', { waitUntil: 'networkidle' });
  await page.setInputFiles('#files', ['examples/points.geojson']);
  await page.waitForFunction(() => document.querySelector('#map-stats').textContent.includes('8 points'));
  await page.fill('#cell_size', '0.02');
  await page.click('#solve');
  await page.waitForSelector('#progress:not([hidden])');
  const label = await page.textContent('#progress-label');
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Done'), null, { timeout: 30000 });
  await page.waitForFunction(() => document.querySelector('#progress').hidden, null, { timeout: 30000 });
  if (!label) throw new Error('progress label empty');
  console.log(JSON.stringify({ label, errors, status: await page.textContent('#status') }));
  await browser.close();
})().catch((err) => { console.error(err); process.exit(1); });
